"""Generate final-report figures and LaTeX numbers from final CV outputs.

Run experiments/validate_final.py first. Figures use the delivered model's
configuration. Earlier exploratory pipelines are kept out of this comparison.
"""

import json
from pathlib import Path
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from experiments.validate_final import metrics
from project_io import load_model, sha256
from final_pipeline import CONFIG

OUT = ROOT / "documentation" / "final_figures"
REPORT = ROOT / "documentation" / "report"


def main():
    source = ROOT / "artifacts" / "validation"
    result_path = source / "results.json"
    data = json.loads(result_path.read_text(encoding="utf-8"))
    # A plot of an old pipeline must not silently be reused for a changed model.
    if data["protocol"]["config"] != CONFIG:
        raise ValueError("Validation settings differ from final_pipeline.CONFIG")
    for name, expected in data["protocol"]["sha256"].items():
        if name.endswith(".py") and sha256(ROOT / name) != expected:
            raise ValueError(f"Validation is stale after a source change: {name}")
    saved_model = ROOT / "artifacts" / "final_model.npz"
    if load_model(saved_model)["config"] != CONFIG:
        raise ValueError("Saved weights belong to a different model configuration")
    r = data["results"]
    with np.load(source / "oof_predictions.npz", allow_pickle=False) as archive:
        y, probability = archive["y"], archive["blend"]
    OUT.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update(
        {
            "font.size": 8,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "savefig.dpi": 240,
            "axes.labelsize": 8,
        }
    )
    thresholds = np.linspace(0.02, 0.65, 127)
    measurements = [metrics(y, probability, t) for t in thresholds]
    fig, ax = plt.subplots(figsize=(3.4, 1.95), layout="constrained")
    for key, label, color in [
        ("f1", "F1", "#1565b0"),
        ("precision", "Precision", "#bd5725"),
        ("recall", "Recall", "#00856f"),
    ]:
        ax.plot(
            thresholds,
            [row[key] for row in measurements],
            label=label,
            color=color,
            lw=1.6,
        )
    threshold = data["protocol"]["config"]["threshold"]
    ax.axvline(threshold, color="#555555", ls="--", lw=0.9)
    ax.set(
        xlabel="Classification threshold",
        ylabel="Pooled OOF metric",
        ylim=(0, 1),
        xlim=(0.02, 0.65),
    )
    ax.legend(frameon=False, loc="upper right", fontsize=7)
    ax.grid(alpha=0.18)
    fig.savefig(OUT / "threshold.png")
    plt.close(fig)

    keys = ["ridge_raw", "newton", "newton_interactions", "gbdt", "blend_locked"]
    labels = [
        "Ridge, raw",
        "Newton",
        "Newton + products",
        "Boosted trees",
        "Blend (delivered)",
    ]
    fig, ax = plt.subplots(figsize=(3.4, 1.85), layout="constrained")
    for i, key in enumerate(keys):
        ax.errorbar(
            r[key]["mean_f1"],
            i,
            xerr=r[key]["std_f1"],
            fmt="o",
            capsize=3,
            color="#00856f" if key == "blend_locked" else "#1565b0",
        )
    ax.set_yticks(range(len(labels)), labels)
    ax.invert_yaxis()
    ax.set_xlabel("Development F1 (fold mean and SD)")
    ax.grid(axis="x", alpha=0.18)
    fig.savefig(OUT / "model_comparison.png")
    plt.close(fig)

    rows = []
    for key, label in zip(keys, labels):
        score = r[key]
        rows.append(
            f"{label} & ${score['mean_f1']:.4f} \\pm {score['std_f1']:.4f}$ & {score['threshold']:.3f} "
            + r"\\"
        )
    table = "\n".join(
        [
            "% Generated by documentation/final_figures.py; do not edit values.",
            r"\begin{tabular}{@{}lcc@{}}",
            r"\toprule",
            r"Model & F1 (mean $\pm$ SD) & Threshold \\",
            r"\midrule",
            *rows,
            r"\bottomrule",
            r"\end{tabular}",
            "",
        ]
    )
    (REPORT / "results_table.tex").write_text(table, encoding="utf-8")
    locked = r["blend_locked"]["pooled_metrics"]
    half = metrics(y, probability, 0.5)
    macros = {
        "FinalFOne": f"{r['blend_locked']['mean_f1']:.4f}",
        "FinalStd": f"{r['blend_locked']['std_f1']:.4f}",
        "TreeGain": f"{r['gbdt']['mean_f1'] - r['newton_interactions']['mean_f1']:.4f}",
        "BlendGain": f"{r['blend_locked']['mean_f1'] - r['gbdt']['mean_f1']:.4f}",
        "InteractionsGain": f"{r['newton_interactions']['mean_f1'] - r['newton']['mean_f1']:.4f}",
        "FinalPrecision": f"{locked['precision'] * 100:.1f}",
        "FinalRecall": f"{locked['recall'] * 100:.1f}",
        "HalfFOne": f"{half['f1']:.4f}",
        "FinalTP": f"{locked['tp']:,}".replace(",", "\\,"),
        "FinalFP": f"{locked['fp']:,}".replace(",", "\\,"),
        "FinalFN": f"{locked['fn']:,}".replace(",", "\\,"),
    }
    text = (
        "% Generated from final pipeline validation.\n"
        + "\n".join(
            f"\\newcommand{{\\{key}}}{{{value}}}" for key, value in macros.items()
        )
        + "\n"
    )
    (REPORT / "results_summary.tex").write_text(text, encoding="utf-8")
    provenance = {
        "results_sha256": sha256(result_path),
        "generator_sha256": sha256(Path(__file__)),
        "validation_signature": data["protocol"]["signature"],
        "reported_model": "final_pipeline.CONFIG",
        "model_sha256": sha256(saved_model),
        "oof_predictions_sha256": sha256(source / "oof_predictions.npz"),
    }
    (OUT / "provenance.json").write_text(
        json.dumps(provenance, indent=2) + "\n", encoding="utf-8"
    )
    print("Final model figures, table and report numbers generated from", result_path)


if __name__ == "__main__":
    main()
